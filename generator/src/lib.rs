//! Turns any input, a text or any bytes, into an audiochaos song: a patch
//! with a clock, a `song` module arranging sections, two to six instruments,
//! a mix and the master.
//!
//! The same input always gives the same patch, for a given [`VERSION`]: the
//! input is hashed into a seed, and everything else is drawn from it with
//! algorithms written out in [`rng`]. The skeleton is fixed so that every
//! song plays; only its contents are drawn. It is not meant to be musical,
//! only a valid patch that makes sound.
//!
//! The generator keeps its own lists of instruments, effects and scales
//! rather than drawing from the library's: a module or scale added to
//! audiochaos must not change the songs that existing inputs give.

mod builder;
mod instrument;
pub mod rng;

use audiochaos::engine::score::{self, SCALES};
use audiochaos::patch::{Patch, PatchSection};

use builder::{Builder, Stage};
use instrument::{Instrument, Key, Kind};
use rng::Rng;

/// Bumped whenever an input could give a different patch than before, so a
/// song is known by its input and this version. Written in the patch's
/// description.
pub const VERSION: u32 = 1;

/// Scales the key is drawn from, by their name in the library.
const SCALE_NAMES: [&str; 12] = [
    "major",
    "minor",
    "harmonic minor",
    "dorian",
    "phrygian",
    "lydian",
    "mixolydian",
    "major pentatonic",
    "minor pentatonic",
    "blues",
    "hirajoshi",
    "whole tone",
];

const ROOTS: [&str; 12] = [
    "C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B",
];

/// Sections between the intro and the outro.
const MIDDLE_SECTIONS: [&str; 6] = ["verse", "chorus", "bridge", "break", "build", "drop"];

/// The song the input gives.
pub fn generate(input: &[u8]) -> Patch {
    let seed = rng::seed(input);
    let mut rng = Rng::new(seed);
    let mut b = Builder::default();

    let tempo = rng.int(70, 170);
    b.module(Stage::Clock, "clock", "clock");
    b.knob("clock", "tempo", tempo as f32);

    let key = draw_key(&mut rng);
    let sections = draw_sections(&mut rng);

    let kinds: Vec<Kind> = (0..rng.int(2, 6)).map(|_| *rng.pick(&Kind::ALL)).collect();
    let names = instrument_names(&kinds);
    let patterns: Vec<usize> = kinds.iter().map(|k| k.draw_patterns(&mut rng)).collect();
    let tracks = draw_tracks(&mut rng, sections.len(), &patterns);

    let mut ends = Vec::new();
    for (t, (&kind, name)) in kinds.iter().zip(&names).enumerate() {
        let track = format!("track {}", t + 1);
        let instrument = Instrument {
            kind,
            name,
            track: &track,
            patterns: patterns[t],
        };
        ends.push(instrument::add(&mut b, &mut rng, &instrument, &key));
    }

    let section_count = sections.len();
    let song = b.module(Stage::Song, "song", "song");
    song.sections = Some(sections);
    song.tracks = Some(tracks);
    b.cable("clock", "bar", "song", "clock");

    b.module(Stage::Master, "master", "master");
    for (m, group) in ends.chunks(4).enumerate() {
        let mix = if m == 0 {
            "mix".to_string()
        } else {
            format!("mix {}", m + 1)
        };
        b.module(Stage::Mix, &mix, "mix");
        for (i, end) in group.iter().enumerate() {
            let input = (i + 1).to_string();
            b.cable(end, "out", &mix, &input);
            b.knob(&mix, &format!("level {input}"), rng.value(0.4, 1.0));
        }
        b.cable(&mix, "out", "master", "in");
    }

    let description = format!(
        "Generated by audiochaos-gen {VERSION} from seed {seed:016x}: {} sections at {tempo} BPM in {}; {}.",
        section_count,
        key.name,
        names.join(", "),
    );
    b.finish(description)
}

fn draw_key(rng: &mut Rng) -> Key {
    let root = rng.below(ROOTS.len());
    let scale = *rng.pick(&SCALE_NAMES);
    let intervals = SCALES
        .iter()
        .find(|(name, _)| *name == scale)
        .map(|(_, intervals)| *intervals)
        .expect("every scale the generator draws exists in the library");
    Key {
        root: root as u8,
        name: format!("{} {scale}", ROOTS[root]),
        intervals,
    }
}

/// An intro, one to six sections, an outro.
fn draw_sections(rng: &mut Rng) -> Vec<PatchSection> {
    let middle = rng.int(1, 6);
    let mut names = vec!["intro"];
    names.extend((0..middle).map(|_| *rng.pick(&MIDDLE_SECTIONS)));
    names.push("outro");
    names
        .into_iter()
        .map(|name| PatchSection {
            name: name.to_string(),
            bars: *rng.pick(&[2, 4, 8]),
        })
        .collect()
}

/// `kick`, `bass`, `kick 2`: each kind numbered from its second instrument.
fn instrument_names(kinds: &[Kind]) -> Vec<String> {
    kinds
        .iter()
        .enumerate()
        .map(
            |(i, kind)| match kinds[..i].iter().filter(|k| *k == kind).count() {
                0 => kind.name().to_string(),
                n => format!("{} {}", kind.name(), n + 1),
            },
        )
        .collect()
}

/// Each instrument's track: per section, a pattern it has or silence. Every
/// instrument plays somewhere, and something plays from the first section,
/// so the song starts right away.
fn draw_tracks(rng: &mut Rng, sections: usize, patterns: &[usize]) -> Vec<String> {
    let mut cells: Vec<Vec<Option<u8>>> = patterns
        .iter()
        .map(|&count| {
            let mut track: Vec<Option<u8>> = (0..sections)
                .map(|_| (!rng.chance(35)).then(|| rng.below(count) as u8))
                .collect();
            if track.iter().all(Option::is_none) {
                track[rng.below(sections)] = Some(0);
            }
            track
        })
        .collect();
    if cells.iter().all(|track| track[0].is_none()) {
        let first = rng.below(cells.len());
        cells[first][0] = Some(0);
    }
    cells
        .into_iter()
        .map(|track| score::cells_text(track.into_iter()))
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn instruments_of_a_kind_are_numbered() {
        let kinds = [Kind::Kick, Kind::Bass, Kind::Kick, Kind::Kick];
        assert_eq!(
            instrument_names(&kinds),
            ["kick", "bass", "kick 2", "kick 3"]
        );
    }

    #[test]
    fn every_track_plays_and_the_first_section_is_not_silent() {
        for seed in 0..200 {
            let mut rng = Rng::new(seed);
            let tracks = draw_tracks(&mut rng, 3, &[1, 4, 2]);
            assert!(
                tracks
                    .iter()
                    .all(|t| t.contains(|c: char| c != '.' && c != ' '))
            );
            assert!(tracks.iter().any(|t| !t.starts_with('.')));
        }
    }

    #[test]
    fn tracks_only_use_the_patterns_their_instrument_has() {
        for seed in 0..200 {
            let mut rng = Rng::new(seed);
            let tracks = draw_tracks(&mut rng, 8, &[1, 2]);
            assert!(!tracks[0].contains(['B', 'C', 'D']));
            assert!(!tracks[1].contains(['C', 'D']));
        }
    }
}
